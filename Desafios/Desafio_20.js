// Desafio 20 - Ordem de operações

const resultado = 2 + 3 * 5;

console.log(resultado);

// Explicação:
// O JavaScript segue a ordem matemática padrão (precedência de operadores):
// multiplicação e divisão são executadas antes de soma e subtração.
// Por isso, "3 * 5" é calculado primeiro (= 15), e só depois somamos
// "2 + 15", resultando em 17.